package com.hakdaar.app.core.model

/**
 * Explicit states of the floating Hakdaar bubble state machine.
 * As required by specification Section 6:
 * DISABLED, IDLE, EXPANDED, LISTENING, TRANSCRIBING, TRANSCRIPT_REVIEW,
 * MATCHING_TASK, COLLECTING_FIELDS, FIELD_REVIEW, OPENING_TARGET,
 * WAITING_FOR_PAGE, WAITING_FOR_FIELD_FOCUS, AWAITING_FILL_CONFIRMATION,
 * FILLING, HANDOVER, PAUSED, ERROR, COMPLETED.
 */
enum class BubbleState {
    DISABLED,
    IDLE,
    EXPANDED,
    LISTENING,
    TRANSCRIBING,
    TRANSCRIPT_REVIEW,
    MATCHING_TASK,
    COLLECTING_FIELDS,
    FIELD_REVIEW,
    OPENING_TARGET,
    WAITING_FOR_PAGE,
    WAITING_FOR_FIELD_FOCUS,
    AWAITING_FILL_CONFIRMATION,
    FILLING,
    HANDOVER,
    PAUSED,
    ERROR,
    COMPLETED
}
